func (g *generator) topVarIdent(name string) string {
	return "_werkTop_" + sanitizeIdent(name)
}

func (g *generator) localVarIdent(name string) string {
	if g.topVars[name] {
		return g.topVarIdent(name)
	}
	return safeLocalIdent(name)
}

func safeLocalIdent(name string) string {
	return "_w_" + sanitizeIdent(name)
}

func sanitizeIdent(s string) string {
	var b strings.Builder
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}

func copyScope(in map[string]bool) map[string]bool {
	out := make(map[string]bool, len(in))
	for k, v := range in {
		out[k] = v
	}
	return out
}

func isPklURI(s string) bool {
	return strings.HasPrefix(s, "package://") || strings.HasPrefix(s, "https://") || strings.HasPrefix(s, "http://") || strings.HasPrefix(s, "file://")
}

func defaultImportAlias(spec string) string {
	s := spec
	for _, pfx := range []string{"go:", "mage:"} {
		s = strings.TrimPrefix(s, pfx)
	}
	if idx := strings.LastIndex(s, "@"); idx > 0 && !strings.HasPrefix(spec, "package://") {
		s = s[:idx]
	}
	base := filepath.Base(s)
	base = strings.TrimSuffix(base, filepath.Ext(base))
	return strings.ReplaceAll(base, "-", "_")
}

func (g *generator) writeIndent() {
	for i := 0; i < g.indent; i++ {
		g.b.WriteByte('\t')
	}
}

func (g *generator) line(s string) {
	if s == "" {
		g.b.WriteByte('\n')
		return
	}
	g.writeIndent()
	g.b.WriteString(s)
	g.b.WriteByte('\n')
}

