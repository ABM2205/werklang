package codegen

import (
	"fmt"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/ABM2205/werklang/internal/lexer"
	"github.com/ABM2205/werklang/internal/parser"
	"github.com/ABM2205/werklang/internal/types"
)

type Options struct {
	DefaultPklBin string
}

type generator struct {
	cp            *types.CheckedProgram
	opts          Options
	b             strings.Builder
	indent        int
	tmpCounter    int
	goAliasMap     map[string]string // werklang alias -> generated Go import ident
	mageAliasMap   map[string]string // werklang alias -> generated Go import ident
	usedGoIdents   map[string]bool
	usedMageIdents map[string]bool
	topVars       map[string]bool
	selfFieldRecv string // non-empty when emitting expressions inside a struct .recompute() method
}

// Generate emits a complete //go:build mage Go source file from a typechecked Program.
func Generate(cp *types.CheckedProgram, opts Options) (string, error) {
	g := &generator{
		cp:             cp,
		opts:           opts,
		goAliasMap:     make(map[string]string),
		mageAliasMap:   make(map[string]string),
		usedGoIdents:   make(map[string]bool),
		usedMageIdents: make(map[string]bool),
		topVars:        make(map[string]bool),
	}
	return g.emitAll(), nil
}

func unexportGoType(goTypeName string) string {
	if goTypeName == "" {
		return "werkStruct"
	}
	return strings.ToLower(goTypeName[:1]) + goTypeName[1:]
}

func (g *generator) goTypeString(t types.Type) string {
	switch tt := t.(type) {
	case *types.BasicType:
		switch tt.Kind {
		case types.KindInt:
			return "int"
		case types.KindFloat:
			return "float64"
		case types.KindString:
			return "string"
		case types.KindBool:
			return "bool"
		default:
			return "any"
		}
	case *types.SliceType:
		if tt.Elem == nil || tt.Elem == types.Any {
			return "[]any"
		}
		return "[]" + g.goTypeString(tt.Elem)
	case *types.ModuleType:
		if tt.SourceKind == types.ModGoStruct {
			return tt.GoTypeName
		}
		return unexportGoType(tt.GoTypeName)
	default:
		return "any"
	}
}

func (g *generator) emitAll() string {
	// Pre-assign Go import aliases for go:... and mage:... imports
	for i, gp := range g.cp.GoImports {
		g.goAliasMap[gp.Alias] = fmt.Sprintf("_go_%d_%s", i, sanitizeIdent(gp.Alias))
	}
	for i, mp := range g.cp.MageImports {
		g.mageAliasMap[mp.Alias] = fmt.Sprintf("_mage_%d_%s", i, sanitizeIdent(mp.Alias))
	}

	// Render body into a separate buffer first so we know which _mage_X named imports were referenced!
	bodyGen := *g
	bodyGen.b = strings.Builder{}
	bodyGen.emitDeclarationsAndTargets()
	bodyCode := bodyGen.b.String()
	g.usedGoIdents = bodyGen.usedGoIdents
	g.usedMageIdents = bodyGen.usedMageIdents

	hasPkl := len(g.cp.PklModules) > 0

	g.line("// Code generated by werklang. DO NOT EDIT.")
	g.line("//go:build mage")
	g.line("")
	g.line("package main")
	g.line("")
	g.line("import (")
	g.indent++
	if hasPkl {
		g.line(`"context"`)
	}
	g.line(`"fmt"`)
	g.line(`"io/fs"`)
	g.line(`"os"`)
	g.line(`"path/filepath"`)
	g.line(`"regexp"`)
	g.line(`"sort"`)
	g.line(`"strconv"`)
	g.line(`"strings"`)
	g.line(`"sync"`)
	g.line("")
	if hasPkl {
		g.line(`pkl "github.com/apple/pkl-go/pkl"`)
	}
	g.line(`mg "github.com/magefile/mage/mg"`)
	g.line(`magesh "github.com/magefile/mage/sh"`)
	g.line(`magetarget "github.com/magefile/mage/target"`)

	if len(g.cp.GoImports) > 0 {
		g.line("")
		for _, gp := range g.cp.GoImports {
			goIdent := g.goAliasMap[gp.Alias]
			if g.usedGoIdents[goIdent] {
				g.linef("%s %q", goIdent, gp.ImportPath)
			}
		}
	}

	if len(g.cp.MageImports) > 0 {
		g.line("")
		for _, mp := range g.cp.MageImports {
			// Blank import with // mage:import directive exposes targets to `werk -l` & CLI
			g.linef("// mage:import %s", mp.Alias)
			g.linef("_ %q", mp.ImportPath)
			goIdent := g.mageAliasMap[mp.Alias]
			if g.usedMageIdents[goIdent] {
				g.linef("%s %q", goIdent, mp.ImportPath)
			}
		}
	}
	g.indent--
	g.line(")")
	g.line("")

	// Suppress unused import errors across arbitrary scripts
	g.line("var (")
	g.indent++
	g.line("_ = fmt.Println")
	g.line("_ = fs.SkipDir")
	g.line("_ = os.Getenv")
	g.line("_ = filepath.Join")
	g.line("_ = regexp.Compile")
	g.line("_ = sort.Strings")
	g.line("_ = strconv.Itoa")
	g.line("_ = strings.TrimSpace")
	g.line("_ = mg.SerialDeps")
	g.line("_ = magesh.RunV")
	g.line("_ = magetarget.Path")
	for _, gp := range g.cp.GoImports {
		// Reference package safely if needed: handled only when imported; Go requires at least one ref
		_ = gp
	}
	g.indent--
	g.line(")")
	g.line("")

	g.b.WriteString(bodyCode)
	g.emitRuntimeHelpers(hasPkl)
	return g.b.String()
}

func (g *generator) emitDeclarationsAndTargets() {
	// Pre-populate g.topVars so inline `config` field defaults can reference top-level fields (e.g. `release`).
	for _, imp := range g.cp.Prog.Imports {
		alias := imp.Alias
		if alias == "" {
			alias = defaultImportAlias(imp.Path)
		}
		if sym := g.cp.TopScope.LookupLocal(alias); sym != nil && sym.Kind == types.SymModule {
			g.topVars[alias] = true
		}
	}
	for _, cm := range g.cp.ConfigModules {
		g.topVars[cm.Name] = true
	}
	for _, mf := range g.cp.SelfModule.Fields {
		g.topVars[mf.Name] = true
	}

	// 1. Emit Go struct definitions for imported .werk modules, .pkl modules, and inline `config` blocks
	emittedStructs := make(map[string]bool)
	for _, m := range g.cp.WerkModules {
		if !emittedStructs[m.GoTypeName] {
			emittedStructs[m.GoTypeName] = true
			g.emitWerkOrConfigStruct(m)
		}
	}
	for _, m := range g.cp.PklModules {
		if !emittedStructs[m.GoTypeName] {
			emittedStructs[m.GoTypeName] = true
			g.emitPklStruct(m)
		}
	}
	for _, m := range g.cp.ConfigModules {
		if !emittedStructs[m.GoTypeName] {
			emittedStructs[m.GoTypeName] = true
			g.emitWerkOrConfigStruct(m)
		}
	}

	// 2. Emit top-level variables for imported modules, configs, and top-level FieldDecls
	g.line("// --- Top-level state ---")
	for _, imp := range g.cp.Prog.Imports {
		alias := imp.Alias
		if alias == "" {
			alias = defaultImportAlias(imp.Path)
		}
		sym := g.cp.TopScope.LookupLocal(alias)
		if sym == nil || sym.Kind != types.SymModule {
			continue
		}
		mt, ok := sym.Type.(*types.ModuleType)
		if !ok {
			continue
		}
		vName := g.topVarIdent(alias)
		g.topVars[alias] = true
		g.linef("var %s %s", vName, g.goTypeString(mt))
	}

	for _, cm := range g.cp.ConfigModules {
		vName := g.topVarIdent(cm.Name)
		g.topVars[cm.Name] = true
		g.linef("var %s %s", vName, g.goTypeString(cm))
	}

	// Inherited fields from `amends` + top-level fields
	for _, mf := range g.cp.SelfModule.Fields {
		vName := g.topVarIdent(mf.Name)
		g.topVars[mf.Name] = true
		g.linef("var %s %s", vName, g.goTypeString(mf.Type))
	}
	g.line("")

	// 3. Emit lazy one-time initializer `werkEnsureInit()`
	g.line("var werkInitOnce sync.Once")
	g.line("var werkInitErr error")
	g.line("")
	g.line("func werkEnsureInit() error {")
	g.indent++
	g.line("werkInitOnce.Do(func() {")
	g.indent++
	g.line("defer werkRecover(&werkInitErr)")

	// 3a. Initialize imported .werk & .pkl modules
	for _, imp := range g.cp.Prog.Imports {
		alias := imp.Alias
		if alias == "" {
			alias = defaultImportAlias(imp.Path)
		}
		sym := g.cp.TopScope.LookupLocal(alias)
		if sym == nil || sym.Kind != types.SymModule {
			continue
		}
		mt, ok := sym.Type.(*types.ModuleType)
		if !ok {
			continue
		}
		vName := g.topVarIdent(alias)
		if mt.SourceKind == types.ModPkl {
			srcArg := imp.Path
			if !isPklURI(srcArg) && !filepath.IsAbs(srcArg) {
				srcArg = filepath.Join(filepath.Dir(g.cp.Prog.Path), srcArg)
				if abs, err := filepath.Abs(srcArg); err == nil {
					srcArg = abs
				}
			}
			g.linef("%s = load_%s(%q, %t)", vName, unexportGoType(mt.GoTypeName), srcArg, isPklURI(imp.Path))
		} else if mt.SourceKind == types.ModWerk {
			g.linef("%s = new_%s()", vName, unexportGoType(mt.GoTypeName))
		}
	}

	// 3b. If `amends` was used, seed inherited defaults first
	hasTargets := len(g.cp.TargetOrder) > 0
	if g.cp.BaseModule != nil {
		baseVar := "_werkBase"
		if g.cp.BaseModule.SourceKind == types.ModPkl {
			srcArg := g.cp.BaseModule.SourcePath
			g.linef("%s := load_%s(%q, %t)", baseVar, unexportGoType(g.cp.BaseModule.GoTypeName), srcArg, isPklURI(srcArg))
		} else {
			g.linef("%s := new_%s()", baseVar, unexportGoType(g.cp.BaseModule.GoTypeName))
		}
		for _, bf := range g.cp.BaseModule.Fields {
			g.linef("%s = %s.%s", g.topVarIdent(bf.Name), baseVar, bf.GoFieldName)
		}
	}

	// 3c. Execute top-level items in source order:
	// If the file has targets, top-level runs config + field initializers (and top-level setup stmts).
	// If the file has NO targets (script mode!), top-level imperative statements run inside the generated `Run` target!
	initScope := make(map[string]bool)
	for k := range g.topVars {
		initScope[k] = true
	}
	for _, item := range g.cp.Prog.Items {
		switch n := item.(type) {
		case *parser.ConfigDecl:
			cm := g.findConfigModule(n.Name)
			if cm != nil {
				g.linef("%s = new_%s()", g.topVarIdent(cm.Name), unexportGoType(cm.GoTypeName))
			}
		case *parser.FieldDecl:
			if hasTargets {
				g.emitTopFieldInit(n)
			}
		case *parser.TargetDecl, *parser.AmendsClause, *parser.ImportDecl:
			// handled elsewhere
		case parser.Stmt:
			if hasTargets {
				g.emitStmt(n, initScope)
			}
		}
	}

	// If `amends` was used on a .werk module and we have targets, recompute inherited derived fields
	if hasTargets && g.cp.BaseModule != nil && g.cp.BaseModule.SourceKind == types.ModWerk {
		g.emitAmendsDerivedRecompute()
	}

	g.indent--
	g.line("})")
	g.line("return werkInitErr")
	g.indent--
	g.line("}")
	g.line("")

	// 4. Emit Targets (or standalone Script Default target if no targets declared)
	if !hasTargets {
		g.line("var Default = Run")
		g.line("")
		g.line("// Run executes the standalone Werklang script.")
		g.line("func Run() (retErr error) {")
		g.indent++
		g.line("defer werkRecover(&retErr)")
		g.line("if err := werkEnsureInit(); err != nil {")
		g.indent++
		g.line("return err")
		g.indent--
		g.line("}")
		scriptScope := make(map[string]bool)
		for k := range g.topVars {
			scriptScope[k] = true
		}
		for _, item := range g.cp.Prog.Items {
			switch n := item.(type) {
			case *parser.FieldDecl:
				g.emitTopFieldInit(n)
			case parser.Stmt:
				g.emitStmt(n, scriptScope)
			}
		}
		if g.cp.BaseModule != nil && g.cp.BaseModule.SourceKind == types.ModWerk {
			g.emitAmendsDerivedRecompute()
		}
		g.line("return nil")
		g.indent--
		g.line("}")
		g.line("")
		return
	}

	// Determine Default target (`target default` if present, otherwise first target)
	defaultTarget := g.cp.TargetOrder[0]
	if dt, ok := g.cp.Targets["default"]; ok {
		defaultTarget = dt
		g.linef(`var Aliases = map[string]interface{}{"default": %s}`, dt.GoFuncName)
	}
	g.linef("var Default = %s", defaultTarget.GoFuncName)
	g.line("")

	for _, ti := range g.cp.TargetOrder {
		g.emitTargetFunc(ti)
	}
}

func (g *generator) emitTopFieldInit(fd *parser.FieldDecl) {
	vName := g.topVarIdent(fd.Name)
	if fd.Value != nil {
		g.linef("%s = %s", vName, g.exprString(fd.Value))
	}
	// Support CLI -D key=val overrides (passed via WERK_OVERRIDE_<NAME>)
	ft := g.cp.FieldTypes[fd]
	envKey := "WERK_OVERRIDE_" + fd.Name
	switch ft {
	case types.String:
		g.linef("if _ov, _ok := os.LookupEnv(%q); _ok { %s = _ov }", envKey, vName)
	case types.Bool:
		g.linef("if _ov, _ok := os.LookupEnv(%q); _ok { %s = werkParseBool(%q, _ov) }", envKey, vName, fd.Name)
	case types.Int:
		g.linef("if _ov, _ok := os.LookupEnv(%q); _ok { %s = werkParseInt(%q, _ov) }", envKey, vName, fd.Name)
	case types.Float:
		g.linef("if _ov, _ok := os.LookupEnv(%q); _ok { %s = werkParseFloat(%q, _ov) }", envKey, vName, fd.Name)
	}
	if g.cp.BaseModule != nil && g.cp.BaseModule.SourceKind == types.ModWerk {
		g.emitAmendsDerivedRecompute()
	}
}

func (g *generator) emitAmendsDerivedRecompute() {
	// Re-evaluate inherited derived fields that weren't explicitly overridden in this file
	overriddenHere := make(map[string]bool)
	for _, fd := range g.cp.Prog.Fields {
		overriddenHere[fd.Name] = true
	}
	for _, bf := range g.cp.BaseModule.Fields {
		if bf.Derived && bf.DefaultExpr != nil && !overriddenHere[bf.Name] {
			g.linef("%s = %s", g.topVarIdent(bf.Name), g.exprString(bf.DefaultExpr))
		}
	}
}

func (g *generator) emitWerkOrConfigStruct(m *types.ModuleType) {
	structName := unexportGoType(m.GoTypeName)
	g.linef("type %s struct {", structName)
	g.indent++
	for _, f := range m.Fields {
		g.linef("%s %s", f.GoFieldName, g.goTypeString(f.Type))
	}
	for _, f := range m.Fields {
		if f.Derived {
			g.linef("_override_%s bool", f.GoFieldName)
		}
	}
	g.indent--
	g.line("}")
	g.line("")

	// Constructor `new_<structName>()`
	g.linef("func new_%s() %s {", structName, structName)
	g.indent++
	g.linef("var s %s", structName)
	prevRecv := g.selfFieldRecv
	g.selfFieldRecv = "s"
	prevTop := g.topVars
	if m.SourceKind == types.ModWerk {
		// Inside an imported .werk module constructor, field names resolve on `s.`, not root file globals
		g.topVars = map[string]bool{}
	}
	for _, f := range m.Fields {
		if f.DefaultExpr != nil {
			g.linef("s.%s = %s", f.GoFieldName, g.exprForModuleField(m, f.DefaultExpr))
		}
	}
	g.line("return s")
	g.indent--
	g.line("}")
	g.line("")

	// Recompute method for derived fields after `{ ... }` amending
	g.linef("func (s *%s) recompute() {", structName)
	g.indent++
	for _, f := range m.Fields {
		if f.Derived && f.DefaultExpr != nil {
			g.linef("if !s._override_%s {", f.GoFieldName)
			g.indent++
			g.linef("s.%s = %s", f.GoFieldName, g.exprForModuleField(m, f.DefaultExpr))
			g.indent--
			g.line("}")
		}
	}
	g.topVars = prevTop
	g.selfFieldRecv = prevRecv
	g.indent--
	g.line("}")
	g.line("")
}

func (g *generator) exprForModuleField(m *types.ModuleType, e parser.Expr) string {
	// Temporarily bind module fields onto receiver `s.<GoFieldName>`
	saved := make(map[string]string)
	for _, f := range m.Fields {
		saved[f.Name] = f.GoFieldName
	}
	return g.exprStringWithModuleScope(e, saved)
}

func (g *generator) emitPklStruct(m *types.ModuleType) {
	structName := unexportGoType(m.GoTypeName)
	g.linef("type %s struct {", structName)
	g.indent++
	for _, f := range m.Fields {
		g.linef("%s %s", f.GoFieldName, g.goTypeString(f.Type))
	}
	g.indent--
	g.line("}")
	g.line("")

	g.linef("func (s *%s) recompute() {}", structName)
	g.line("")

	g.linef("func decode_%s(obj *pkl.Object) %s {", structName, structName)
	g.indent++
	g.linef("var s %s", structName)
	g.line("if obj == nil { return s }")
	for _, f := range m.Fields {
		g.linef("if raw, ok := obj.Properties[%q]; ok {", f.Name)
		g.indent++
		g.linef("s.%s = %s", f.GoFieldName, g.pklDecodeExpr("raw", f.Type))
		g.indent--
		g.line("}")
	}
	g.line("return s")
	g.indent--
	g.line("}")
	g.line("")

	g.linef("func load_%s(src string, isURI bool) %s {", structName, structName)
	g.indent++
	g.line("obj := werkEvalPklObject(src, isURI)")
	g.linef("return decode_%s(obj)", structName)
	g.indent--
	g.line("}")
	g.line("")
}

func (g *generator) pklDecodeExpr(rawExpr string, t types.Type) string {
	switch tt := t.(type) {
	case *types.BasicType:
		switch tt.Kind {
		case types.KindInt:
			return fmt.Sprintf("werkPklInt(%s)", rawExpr)
		case types.KindFloat:
			return fmt.Sprintf("werkPklFloat(%s)", rawExpr)
		case types.KindString:
			return fmt.Sprintf("werkPklString(%s)", rawExpr)
		case types.KindBool:
			return fmt.Sprintf("werkPklBool(%s)", rawExpr)
		}
	case *types.SliceType:
		elemGo := g.goTypeString(tt.Elem)
		inner := g.pklDecodeExpr("_el", tt.Elem)
		return fmt.Sprintf("werkPklSlice[%s](%s, func(_el any) %s { return %s })", elemGo, rawExpr, elemGo, inner)
	case *types.ModuleType:
		return fmt.Sprintf("decode_%s(werkPklObj(%s))", unexportGoType(tt.GoTypeName), rawExpr)
	}
	return rawExpr
}

func (g *generator) emitTargetFunc(ti *types.TargetInfo) {
	if ti.Desc != "" {
		for i, line := range strings.Split(ti.Desc, "\n") {
			if i == 0 {
				g.linef("// %s %s", ti.GoFuncName, line)
			} else {
				g.linef("// %s", line)
			}
		}
	} else {
		g.linef("// %s runs target %s.", ti.GoFuncName, ti.Name)
	}

	g.linef("func %s() (retErr error) {", ti.GoFuncName)
	g.indent++
	g.line("defer werkRecover(&retErr)")

	// 1. Dependencies run BEFORE staleness checks (so generated inputs exist first!)
	if len(ti.Deps) > 0 {
		depRefs := make([]string, 0, len(ti.Deps))
		for _, d := range ti.Deps {
			depRefs = append(depRefs, g.resolveTargetFuncExpr(d))
		}
		g.linef("mg.SerialDeps(%s)", strings.Join(depRefs, ", "))
	}
	if len(ti.ParallelDeps) > 0 {
		depRefs := make([]string, 0, len(ti.ParallelDeps))
		for _, d := range ti.ParallelDeps {
			depRefs = append(depRefs, g.resolveTargetFuncExpr(d))
		}
		g.linef("mg.Deps(%s)", strings.Join(depRefs, ", "))
	}

	// 2. Ensure top-level config/modules are initialized
	g.line("if err := werkEnsureInit(); err != nil {")
	g.indent++
	g.line("return err")
	g.indent--
	g.line("}")

	// 3. Optional Makefile-style incremental build check via github.com/magefile/mage/target
	if ti.InputsExpr != nil && ti.OutputsExpr != nil {
		g.linef("_inputs := %s", g.exprString(ti.InputsExpr))
		g.linef("_outputs := %s", g.exprString(ti.OutputsExpr))
		g.line("if len(_inputs) > 0 && len(_outputs) > 0 {")
		g.indent++
		g.line("_needsRun, _err := werkTargetsNeedRebuild(_outputs, _inputs)")
		g.line("if _err != nil { return _err }")
		g.line("if !_needsRun { return nil }")
		g.indent--
		g.line("}")
	}

	// 4. Target body statements
	localScope := make(map[string]bool)
	for k := range g.topVars {
		localScope[k] = true
	}
	for _, st := range ti.ExecStmts {
		g.emitStmt(st, localScope)
	}

	g.line("return nil")
	g.indent--
	g.line("}")
	g.line("")
}

func (g *generator) resolveTargetFuncExpr(dep string) string {
	if local, ok := g.cp.Targets[dep]; ok {
		return local.GoFuncName
	}
	if idx := strings.IndexByte(dep, ':'); idx > 0 {
		ns := dep[:idx]
		tName := dep[idx+1:]
		for _, mp := range g.cp.MageImports {
			if mp.Alias == ns {
				goPkg := g.mageAliasMap[mp.Alias]
				g.usedMageIdents[goPkg] = true
				tgt, ok := mp.Targets[strings.ToLower(tName)]
				if !ok {
					tgt = mp.Targets[tName]
				}
				if tgt != nil {
					if tgt.Namespace != "" {
						return fmt.Sprintf("(%s.%s).%s", goPkg, tgt.Namespace, tgt.Name)
					}
					return fmt.Sprintf("%s.%s", goPkg, tgt.Name)
				}
			}
		}
	}
	return types.ExportGoIdent(dep)
}

func (g *generator) emitStmt(st parser.Stmt, scope map[string]bool) {
	switch s := st.(type) {
	case *parser.FieldDecl:
		varName := g.localVarIdent(s.Name)
		valStr := g.exprString(s.Value)
		if scope[s.Name] {
			g.linef("%s = %s", varName, valStr)
		} else {
			scope[s.Name] = true
			ft := g.cp.FieldTypes[s]
			if ft != nil && ft != types.Invalid {
				g.linef("var %s %s = %s", varName, g.goTypeString(ft), valStr)
			} else {
				g.linef("%s := %s", varName, valStr)
			}
			g.linef("_ = %s", varName)
		}

	case *parser.IfStmt:
		g.emitIfStmt(s, scope)

	case *parser.ForStmt:
		idxIdent := "_"
		innerScope := copyScope(scope)
		if s.IndexVar != "" {
			idxIdent = safeLocalIdent(s.IndexVar)
			innerScope[s.IndexVar] = true
		}
		itemIdent := safeLocalIdent(s.ItemVar)
		innerScope[s.ItemVar] = true
		g.linef("for %s, %s := range %s {", idxIdent, itemIdent, g.exprString(s.Iterable))
		g.indent++
		if s.IndexVar != "" {
			g.linef("_ = %s", idxIdent)
		}
		g.linef("_ = %s", itemIdent)
		for _, child := range s.Body {
			g.emitStmt(child, innerScope)
		}
		g.indent--
		g.line("}")

	case *parser.ExprStmt:
		g.line(g.exprString(s.Expr))
	}
}

func (g *generator) emitIfStmt(s *parser.IfStmt, scope map[string]bool) {
	g.emitIfStmtInline(s, scope, true)
}

func (g *generator) emitIfStmtInline(s *parser.IfStmt, scope map[string]bool, writeLeadingIndent bool) {
	if writeLeadingIndent {
		g.writeIndent()
	}
	g.b.WriteString(fmt.Sprintf("if %s {\n", g.exprString(s.Cond)))
	g.indent++
	thenScope := copyScope(scope)
	for _, child := range s.Then {
		g.emitStmt(child, thenScope)
	}
	g.indent--
	if len(s.Else) == 0 {
		g.line("}")
		return
	}
	if len(s.Else) == 1 {
		if nested, ok := s.Else[0].(*parser.IfStmt); ok {
			g.writeIndent()
			g.b.WriteString("} else ")
			g.emitIfStmtInline(nested, scope, false)
			return
		}
	}
	g.line("} else {")
	g.indent++
	elseScope := copyScope(scope)
	for _, child := range s.Else {
		g.emitStmt(child, elseScope)
	}
	g.indent--
	g.line("}")
}

func (g *generator) exprString(e parser.Expr) string {
	return g.exprStringWithModuleScope(e, nil)
}

func (g *generator) exprStringWithModuleScope(e parser.Expr, modScope map[string]string) string {
	if e == nil {
		return ""
	}
	switch x := e.(type) {
	case *parser.IntLit:
		return strconv.FormatInt(x.Value, 10)
	case *parser.FloatLit:
		if !strings.Contains(x.Raw, ".") {
			return x.Raw + ".0"
		}
		return x.Raw
	case *parser.BoolLit:
		if x.Value {
			return "true"
		}
		return "false"
	case *parser.StringLit:
		return strconv.Quote(x.Value)

	case *parser.InterpStringExpr:
		var fmtStr strings.Builder
		var args []string
		for i, p := range x.Parts {
			fmtStr.WriteString(strings.ReplaceAll(p, "%", "%%"))
			if i < len(x.Exprs) {
				sub := x.Exprs[i]
				if g.cp.ExprTypes[sub] == types.String {
					fmtStr.WriteString("%s")
				} else {
					fmtStr.WriteString("%v")
				}
				args = append(args, g.exprStringWithModuleScope(sub, modScope))
			}
		}
		if len(args) == 0 {
			return strconv.Quote(fmtStr.String())
		}
		return fmt.Sprintf("fmt.Sprintf(%s, %s)", strconv.Quote(fmtStr.String()), strings.Join(args, ", "))

	case *parser.IdentExpr:
		if modScope != nil {
			if goField, ok := modScope[x.Name]; ok {
				return fmt.Sprintf("%s.%s", g.selfFieldRecv, goField)
			}
		}
		if g.topVars[x.Name] {
			return g.topVarIdent(x.Name)
		}
		return safeLocalIdent(x.Name)

	case *parser.SliceLit:
		slType, _ := g.cp.ExprTypes[x].(*types.SliceType)
		elemGo := "string"
		if slType != nil && slType.Elem != nil && slType.Elem != types.Any {
			elemGo = g.goTypeString(slType.Elem)
		}
		var elems []string
		for _, el := range x.Elems {
			elems = append(elems, g.exprStringWithModuleScope(el, modScope))
		}
		return fmt.Sprintf("[]%s{%s}", elemGo, strings.Join(elems, ", "))

	case *parser.IfExpr:
		resGo := g.goTypeString(g.cp.ExprTypes[x])
		cond := g.exprStringWithModuleScope(x.Cond, modScope)
		thenCode := g.exprStringWithModuleScope(x.Then, modScope)
		elseCode := g.exprStringWithModuleScope(x.Else, modScope)
		return fmt.Sprintf("func() %s { if %s { return %s }; return %s }()", resGo, cond, thenCode, elseCode)

	case *parser.UnaryExpr:
		return fmt.Sprintf("(%s%s)", x.Op, g.exprStringWithModuleScope(x.Operand, modScope))

	case *parser.BinaryExpr:
		lt := g.cp.ExprTypes[x.Left]
		lhs := g.exprStringWithModuleScope(x.Left, modScope)
		rhs := g.exprStringWithModuleScope(x.Right, modScope)
		if x.Op == lexer.TokPlus {
			if sl, ok := lt.(*types.SliceType); ok {
				elemGo := g.goTypeString(sl.Elem)
				if sl.Elem == types.Any {
					if rsl, ok := g.cp.ExprTypes[x.Right].(*types.SliceType); ok {
						elemGo = g.goTypeString(rsl.Elem)
					}
				}
				return fmt.Sprintf("werkConcatSlices[%s](%s, %s)", elemGo, lhs, rhs)
			}
		}
		return fmt.Sprintf("(%s %s %s)", lhs, x.Op, rhs)

	case *parser.SelectorExpr:
		if id, ok := x.X.(*parser.IdentExpr); ok {
			if goAlias, isGoPkg := g.goAliasMap[id.Name]; isGoPkg {
				g.usedGoIdents[goAlias] = true
				// Go package var/const access
				sym := g.cp.SelSymbols[x]
				raw := fmt.Sprintf("%s.%s", goAlias, x.Sel)
				if sym != nil {
					if gp, ok := g.cp.TopScope.Lookup(id.Name).Type.(*types.GoPackageType); ok {
						if vr, ok := gp.Vars[x.Sel]; ok {
							return applyReturnCast(raw, vr.Cast)
						}
					}
				}
				return raw
			}
		}
		baseType := g.cp.ExprTypes[x.X]
		if mt, ok := baseType.(*types.ModuleType); ok {
			if mf, ok := mt.FieldMap[x.Sel]; ok {
				return fmt.Sprintf("%s.%s", g.exprStringWithModuleScope(x.X, modScope), mf.GoFieldName)
			}
		}
		return fmt.Sprintf("%s.%s", g.exprStringWithModuleScope(x.X, modScope), x.Sel)

	case *parser.IndexExpr:
		return fmt.Sprintf("%s[%s]", g.exprStringWithModuleScope(x.X, modScope), g.exprStringWithModuleScope(x.Index, modScope))

	case *parser.CallExpr:
		return g.emitCallExpr(x, modScope)

	case *parser.StructAmendExpr:
		return g.emitStructAmendExpr(x, modScope)
	}
	return ""
}

func (g *generator) emitCallExpr(call *parser.CallExpr, modScope map[string]string) string {
	// 1. Built-ins
	if id, ok := call.Callee.(*parser.IdentExpr); ok {
		var args []string
		for _, a := range call.Args {
			args = append(args, g.exprStringWithModuleScope(a, modScope))
		}
		switch id.Name {
		case "sh":
			return fmt.Sprintf(`werkCheck(magesh.RunV("sh", "-c", %s))`, args[0])
		case "exec":
			return fmt.Sprintf(`werkCheck(magesh.RunV(%s, %s...))`, args[0], args[1])
		case "capture":
			return fmt.Sprintf(`werkMust(magesh.Output("sh", "-c", %s))`, args[0])
		case "try_sh":
			return fmt.Sprintf(`magesh.ExitStatus(magesh.Run("sh", "-c", %s))`, args[0])
		case "rm":
			return fmt.Sprintf(`werkCheck(magesh.Rm(%s))`, args[0])
		case "mkdir":
			return fmt.Sprintf(`werkCheck(os.MkdirAll(%s, 0o755))`, args[0])
		case "env":
			if len(args) == 1 {
				return fmt.Sprintf(`werkEnv(%s, "")`, args[0])
			}
			return fmt.Sprintf(`werkEnv(%s, %s)`, args[0], args[1])
		case "glob":
			return fmt.Sprintf(`werkGlob(%s)`, args[0])
		case "exists":
			return fmt.Sprintf(`werkExists(%s)`, args[0])
		case "print":
			return fmt.Sprintf(`fmt.Println(%s)`, strings.Join(args, ", "))
		case "fail":
			return fmt.Sprintf(`werkCheck(mg.Fatal(1, %s))`, args[0])
		}
	}

	// 2. Imported Go function or Mage target call
	if sel, ok := call.Callee.(*parser.SelectorExpr); ok {
		sym := g.cp.SelSymbols[sel]
		if id, ok := sel.X.(*parser.IdentExpr); ok && sym != nil {
			if sym.GoFunc != nil {
				goPkg := g.goAliasMap[id.Name]
				g.usedGoIdents[goPkg] = true
				fn := sym.GoFunc
				var callArgs []string
				for i, a := range call.Args {
					rawArg := g.exprStringWithModuleScope(a, modScope)
					var param types.GoParam
					if i < len(fn.Params) {
						param = fn.Params[i]
					} else if len(fn.Params) > 0 && fn.Params[len(fn.Params)-1].Variadic {
						param = fn.Params[len(fn.Params)-1]
					}
					callArgs = append(callArgs, applyParamCast(rawArg, param))
				}
				rawCall := fmt.Sprintf("%s.%s(%s)", goPkg, fn.Name, strings.Join(callArgs, ", "))
				if fn.ReturnsError {
					if fn.ResultWerkType == types.Void {
						return fmt.Sprintf("werkCheck(%s)", rawCall)
					}
					unwrapped := fmt.Sprintf("werkMust(%s)", rawCall)
					return applyReturnCast(unwrapped, fn.ReturnCast)
				}
				return applyReturnCast(rawCall, fn.ReturnCast)
			}

			if sym.MageTarget != nil {
				goPkg := g.mageAliasMap[id.Name]
				g.usedMageIdents[goPkg] = true
				mt := sym.MageTarget
				targetFn := fmt.Sprintf("%s.%s", goPkg, mt.Name)
				if mt.Namespace != "" {
					targetFn = fmt.Sprintf("(%s.%s).%s", goPkg, mt.Namespace, mt.Name)
				}
				if len(call.Args) == 0 {
					return fmt.Sprintf("mg.SerialDeps(%s)", targetFn)
				}
				var mArgs []string
				mArgs = append(mArgs, targetFn)
				for i, a := range call.Args {
					rawArg := g.exprStringWithModuleScope(a, modScope)
					if i < len(mt.Params) {
						rawArg = applyParamCast(rawArg, mt.Params[i])
					}
					mArgs = append(mArgs, rawArg)
				}
				return fmt.Sprintf("mg.SerialDeps(mg.F(%s))", strings.Join(mArgs, ", "))
			}
		}
	}

	return "/* invalid call */"
}

func applyParamCast(expr string, p types.GoParam) string {
	targetType := strings.TrimPrefix(p.GoTypeString, "...")
	switch p.Cast {
	case types.CastStringToBytes:
		return fmt.Sprintf("[]byte(%s)", expr)
	case types.CastIntCast, types.CastFloatCast:
		return fmt.Sprintf("%s(%s)", targetType, expr)
	default:
		return expr
	}
}

func applyReturnCast(expr string, cast types.GoCastKind) string {
	switch cast {
	case types.CastBytesToString:
		return fmt.Sprintf("string(%s)", expr)
	case types.CastIntCast:
		return fmt.Sprintf("int(%s)", expr)
	case types.CastFloatCast:
		return fmt.Sprintf("float64(%s)", expr)
	default:
		return expr
	}
}

func (g *generator) emitStructAmendExpr(sa *parser.StructAmendExpr, modScope map[string]string) string {
	mod, ok := g.cp.ExprTypes[sa].(*types.ModuleType)
	if !ok {
		return "{}"
	}
	structGo := g.goTypeString(mod)
	baseExpr := g.exprStringWithModuleScope(sa.Base, modScope)

	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("func() %s { _cp := %s; ", structGo, baseExpr))
	for _, fd := range sa.Fields {
		mf := mod.FieldMap[fd.Name]
		if mf == nil {
			continue
		}
		sb.WriteString(fmt.Sprintf("_cp.%s = %s; ", mf.GoFieldName, g.exprStringWithModuleScope(fd.Value, modScope)))
		if mf.Derived {
			sb.WriteString(fmt.Sprintf("_cp._override_%s = true; ", mf.GoFieldName))
		}
	}
	sb.WriteString("_cp.recompute(); return _cp }()")
	return sb.String()
}

