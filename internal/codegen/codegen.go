func werkGlob(pattern string) []string {
	if !strings.Contains(pattern, "**") {
		matches, err := filepath.Glob(pattern)
		werkCheck(err)
		sort.Strings(matches)
		if matches == nil {
			return []string{}
		}
		return matches
	}
	parts := strings.SplitN(pattern, "**", 2)
	root := filepath.Clean(parts[0])
	if root == "" {
		root = "."
	}
	rx := werkGlobToRegex(filepath.ToSlash(pattern))
	var matches []string
	if _, err := os.Stat(root); os.IsNotExist(err) {
		return []string{}
	}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if rx.MatchString(filepath.ToSlash(p)) {
			matches = append(matches, p)
		}
		return nil
	})
	werkCheck(err)
	sort.Strings(matches)
	if matches == nil {
		return []string{}
	}
	return matches
}

func werkGlobToRegex(pat string) *regexp.Regexp {
	var b strings.Builder
	b.WriteString("^")
	for i := 0; i < len(pat); i++ {
		if i+1 < len(pat) && pat[i] == '*' && pat[i+1] == '*' {
			if i+2 < len(pat) && pat[i+2] == '/' {
				b.WriteString("(?:.+/)?")
				i += 2
			} else {
				b.WriteString(".*")
				i++
			}
			continue
		}
		switch pat[i] {
		case '*':
			b.WriteString("[^/]*")
		case '?':
			b.WriteString("[^/]")
		case '.', '+', '(', ')', '|', '^', '$', '[', ']', '{', '}', '\\':
			b.WriteByte('\\')
			b.WriteByte(pat[i])
		default:
			b.WriteByte(pat[i])
		}
	}
	b.WriteString("$")
	return regexp.MustCompile(b.String())
}

