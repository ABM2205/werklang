// SpanEntry maps a contiguous 0-indexed line range [WerkStart..WerkEnd] in `.werk`
// to [GoStart..GoEnd] in the lowered `.go` source (columns are preserved 1:1).
type SpanEntry struct {
	WerkStart int
	WerkEnd   int
	GoStart   int
	GoEnd     int
}

// SpanMap translates 0-indexed (line, col) coordinates between `.werk` and lowered `.go`.
type SpanMap struct {
	Entries []SpanEntry
}

func (m *SpanMap) WerkToGo(line, col int) (int, int, bool) {
	if m == nil {
		return line, col, false
	}
	for _, e := range m.Entries {
		if line >= e.WerkStart && line <= e.WerkEnd {
			return e.GoStart + (line - e.WerkStart), col, true
		}
	}
	return line, col, false
}

func (m *SpanMap) GoToWerk(line, col int) (int, int, bool) {
	if m == nil {
		return line, col, false
	}
	for _, e := range m.Entries {
		if line >= e.GoStart && line <= e.GoEnd {
			return e.WerkStart + (line - e.GoStart), col, true
		}
	}
	return line, col, false
}

// LowerOptions configures lowering of a `.werk` script to pure Go (`package main` + `func main()`).
type LowerOptions struct {
	Filename           string
	WorkDir            string
	Scan               *scanner.Result
	Config             *pklschema.CompiledConfig
	EmitLineDirectives bool
	TolerateErrors     bool // For LSP virtual documents while user is mid-edit
}

// LowerResult contains the lowered Go source, bidirectional span map, and any script diagnostics.
type LowerResult struct {
	GoSource string
	SpanMap  *SpanMap
	Imports  []string // Imported Go package paths (for standalone `go.mod` auto-tidy)
	Diags    diag.Diagnostics
}

type itemKind int

const (
	itemImport itemKind = iota
	itemType
	itemConst
	itemFunc
	itemVar
	itemStmt
)

type topItem struct {
	kind      itemKind
	startOff  int
	endOff    int
	startLine int // 0-indexed in .werk
	endLine   int // 0-indexed in .werk
	rawLines  []string

	// Parsed details (when valid)
	funcDecl   *ast.FuncDecl
	varDecls   []*ast.ValueSpec
	defineVars []string // LHS identifiers on top-level `:=`
	definePos  int      // Byte offset within raw chunk of `:=`
	hasDefine  bool
}

// Lower transforms a scanned `.werk` script and its compiled `config` block into
// valid Go source (`package main` + hoisted globals + `func main()`).
func Lower(opts LowerOptions) (*LowerResult, error) {
	scanRes := opts.Scan
	if scanRes == nil {
		return nil, fmt.Errorf("golower.Lower requires non-nil Scan result")
	}

	res := &LowerResult{
		SpanMap: &SpanMap{},
	}
	res.Diags = append(res.Diags, scanRes.Diags...)

	goProj := scanRes.GoProjection()
	projLines := strings.Split(goProj, "\n")

	items, partDiags := partitionTopLevel(opts.Filename, []byte(goProj), projLines, scanRes.Config)
	res.Diags = append(res.Diags, partDiags...)
	if res.Diags.HasErrors() && !opts.TolerateErrors {
		return res, res.Diags
	}

	// Collect imported package paths & local import aliases
	importNameToPkgPath := make(map[string]string)
	for _, it := range items {
		if it.kind == itemImport {
			pkgs, aliases := extractImportPaths(strings.Join(it.rawLines, "\n"))
			res.Imports = append(res.Imports, pkgs...)
			for k, v := range aliases {
				importNameToPkgPath[k] = v
			}
		}
	}

	// Determine which top-level variables must be hoisted to Go package scope
	hoistedTypes, hoistSet := resolveHoistedVariables(opts, items, importNameToPkgPath)

	// Build lowered Go source line-by-line while recording exact SpanMap
	var outLines []string
	emit := func(s string) {
		if s == "" {
			outLines = append(outLines, "")
			return
		}
		parts := strings.Split(strings.TrimSuffix(s, "\n"), "\n")
		outLines = append(outLines, parts...)
	}
	emitLineDirective := func(werkZeroLine int) {
		if opts.EmitLineDirectives && opts.Filename != "" {
			outLines = append(outLines, fmt.Sprintf("//line %s:%d", filepath.ToSlash(opts.Filename), werkZeroLine+1))
		}
	}
	emitMappedLines := func(werkStartLine int, lines []string) {
		if len(lines) == 0 {
			return
		}
		emitLineDirective(werkStartLine)
		goStart := len(outLines)
		outLines = append(outLines, lines...)
		goEnd := len(outLines) - 1
		res.SpanMap.Entries = append(res.SpanMap.Entries, SpanEntry{
			WerkStart: werkStartLine,
			WerkEnd:   werkStartLine + len(lines) - 1,
			GoStart:   goStart,
			GoEnd:     goEnd,
		})
	}

	emit("// Code generated by werk; DO NOT EDIT.")
	emit("package main")
	emit("")

	if opts.Config != nil && opts.Config.NeedsTimeImport {
		emit(`import _werk_time "time"`)
	}

	// 1. Emit user imports
	for _, it := range items {
		if it.kind == itemImport {
			emitMappedLines(it.startLine, it.rawLines)
			emit("")
		}
	}

	// 2. Emit generated Pkl config structs & package-level var
	if opts.Config != nil && strings.TrimSpace(opts.Config.GoDecls) != "" {
		emit(opts.Config.GoDecls)
		emit("")
	}

	// 3. Emit hoisted global `type`, `const`, and `func` declarations
	for _, it := range items {
		switch it.kind {
		case itemType, itemConst, itemFunc:
			emitMappedLines(it.startLine, it.rawLines)
			emit("")
		}
	}

	// 4. Emit hoisted global `var` declarations
	emittedGlobalVar := make(map[string]bool)
	for _, it := range items {
		if it.kind == itemVar {
			// Pure `var x T` without initializer can be emitted verbatim if no Values
			if varHasNoValues(it.varDecls) {
				for _, vs := range it.varDecls {
					for _, id := range vs.Names {
						emittedGlobalVar[id.Name] = true
					}
				}
				emitMappedLines(it.startLine, it.rawLines)
				emit("")
				continue
			}
			for _, vs := range it.varDecls {
				for _, id := range vs.Names {
					if id.Name == "_" || emittedGlobalVar[id.Name] {
						continue
					}
					emittedGlobalVar[id.Name] = true
					vType := hoistedTypes[id.Name]
					if vType == "" {
						vType = "any"
					}
					emit(fmt.Sprintf("var %s %s", id.Name, vType))
				}
			}
		} else if it.kind == itemStmt && it.hasDefine && stmtTouchesHoisted(it.defineVars, hoistSet) {
			for _, vname := range it.defineVars {
				if vname == "_" || emittedGlobalVar[vname] {
					continue
				}
				emittedGlobalVar[vname] = true
				vType := hoistedTypes[vname]
				if vType == "" {
					vType = "any"
				}
				emit(fmt.Sprintf("var %s %s", vname, vType))
			}
		}
	}
	if len(emittedGlobalVar) > 0 {
		emit("")
	}

	// 5. Emit `func main()` containing top-level `var` initializers and statements in source order
	emit("func main() {")
	for _, it := range items {
		switch it.kind {
		case itemVar:
			if varHasNoValues(it.varDecls) {
				continue
			}
			assignLines := rewriteVarToAssignments(it)
			if len(assignLines) > 0 {
				emitMappedLines(it.startLine, assignLines)
			}
		case itemStmt:
			lines := it.rawLines
			if it.hasDefine && stmtTouchesHoisted(it.defineVars, hoistSet) {
				lines = rewriteDefineToAssign(it)
			}
			emitMappedLines(it.startLine, lines)
		}
	}
	emit("}")
	emit("")

	res.GoSource = strings.Join(outLines, "\n")
	if res.Diags.HasErrors() && !opts.TolerateErrors {
		return res, res.Diags
	}
	return res, nil
}

func partitionTopLevel(filename string, proj []byte, projLines []string, cfg *scanner.ConfigBlock) ([]topItem, diag.Diagnostics) {
	var diags diag.Diagnostics
	var items []topItem

	fset := token.NewFileSet()
	file := fset.AddFile(filename, fset.Base(), len(proj))
	var s goscanner.Scanner
	s.Init(file, proj, nil, 0)

	braceDepth := 0
	parenDepth := 0
	bracketDepth := 0

	inItem := false
	var itemStartPos token.Pos
	var firstTok token.Token
	var firstLit string

	seenBodyItem := false
	firstBodyLine := -1

	recordBodySeen := func(line0 int) {
		if !seenBodyItem {
			seenBodyItem = true
			firstBodyLine = line0
		}
	}

	for {
		pos, tok, lit := s.Scan()
		if tok == token.EOF {
			if inItem {
				endOff := len(proj)
				it := buildTopItem(filename, proj, projLines, file, itemStartPos, endOff, firstTok, firstLit, seenBodyItem, &diags)
				if it != nil {
					if it.kind != itemImport {
						recordBodySeen(it.startLine)
					}
					items = append(items, *it)
				}
			}
			break
		}

		if !inItem {
			if tok == token.SEMICOLON {
				continue
			}
			inItem = true
			itemStartPos = pos
			firstTok = tok
			firstLit = lit
		}

		switch tok {
		case token.LBRACE:
			braceDepth++
		case token.RBRACE:
			if braceDepth > 0 {
				braceDepth--
			}
		case token.LPAREN:
			parenDepth++
		case token.RPAREN:
			if parenDepth > 0 {
				parenDepth--
			}
		case token.LBRACK:
			bracketDepth++
		case token.RBRACK:
			if bracketDepth > 0 {
				bracketDepth--
			}
		case token.SEMICOLON:
			if braceDepth == 0 && parenDepth == 0 && bracketDepth == 0 {
				endOff := file.Offset(pos)
				if lit == ";" {
					endOff++
				}
				it := buildTopItem(filename, proj, projLines, file, itemStartPos, endOff, firstTok, firstLit, seenBodyItem, &diags)
				if it != nil {
					if it.kind != itemImport {
						recordBodySeen(it.startLine)
					}
					items = append(items, *it)
				}
				inItem = false
			}
		}
	}

	// Validate that `config` block (if present) appeared in the header before body items
	if cfg != nil && seenBodyItem && cfg.Span.Start.Line > firstBodyLine {
		diags = append(diags, diag.Diagnostic{
			Span:     cfg.KeywordSpan,
			Severity: diag.SeverityError,
			Message:  "config block must appear in the file header before declarations and statements",
		})
	}

	return items, diags
}

func buildTopItem(
	filename string,
	proj []byte,
	projLines []string,
	tfile *token.File,
	startPos token.Pos,
	endOff int,
	firstTok token.Token,
	_ string,
	seenBodyItem bool,
	diags *diag.Diagnostics,
) *topItem {
	startOff := tfile.Offset(startPos)
	if endOff < startOff {
		endOff = startOff
	}
	pStart := tfile.Position(startPos)
	startLine := pStart.Line - 1
	startCol := pStart.Column - 1

	endPosPos := tfile.Position(tfile.Pos(endOff))
	endLine := endPosPos.Line - 1
	if endOff > startOff && endOff <= len(proj) && proj[endOff-1] == '\n' && endLine > startLine {
		endLine--
	}
	if endLine >= len(projLines) {
		endLine = len(projLines) - 1
	}
	if startLine < 0 || startLine > endLine {
		return nil
	}

	rawLines := make([]string, endLine-startLine+1)
	copy(rawLines, projLines[startLine:endLine+1])

	mkSpan := func() diag.Span {
		return diag.Span{
			File:  filename,
			Start: diag.Pos{Offset: startOff, Line: startLine, Col: startCol},
			End:   diag.Pos{Offset: endOff, Line: endLine, Col: 0},
		}
	}

	switch firstTok {
	case token.PACKAGE:
		*diags = append(*diags, diag.Diagnostic{
			Span:     mkSpan(),
			Severity: diag.SeverityError,
			Message:  "package declarations are not allowed in .werk scripts (package main is implicit)",
		})
		return nil

	case token.IMPORT:
		if seenBodyItem {
			*diags = append(*diags, diag.Diagnostic{
				Span:     mkSpan(),
				Severity: diag.SeverityError,
				Message:  "import declarations must appear in the file header before declarations and statements",
			})
		}
		return &topItem{
			kind:      itemImport,
			startOff:  startOff,
			endOff:    endOff,
			startLine: startLine,
			endLine:   endLine,
			rawLines:  rawLines,
		}

	case token.TYPE:
		return &topItem{
			kind:      itemType,
			startOff:  startOff,
			endOff:    endOff,
			startLine: startLine,
			endLine:   endLine,
			rawLines:  rawLines,
		}

	case token.CONST:
		return &topItem{
			kind:      itemConst,
			startOff:  startOff,
			endOff:    endOff,
			startLine: startLine,
			endLine:   endLine,
			rawLines:  rawLines,
		}

	case token.FUNC:
		chunk := strings.Join(rawLines, "\n")
		fset := token.NewFileSet()
		if pf, err := parser.ParseFile(fset, "", "package p\n"+chunk, 0); err == nil && len(pf.Decls) > 0 {
			if fn, ok := pf.Decls[0].(*ast.FuncDecl); ok {
				if fn.Recv == nil && fn.Name != nil && fn.Name.Name == "main" {
					*diags = append(*diags, diag.Diagnostic{
						Span:     mkSpan(),
						Severity: diag.SeverityError,
						Message:  "cannot declare func main in .werk scripts; top-level statements form the main entrypoint",
					})
					return nil
				}
				return &topItem{
					kind:      itemFunc,
					startOff:  startOff,
					endOff:    endOff,
					startLine: startLine,
					endLine:   endLine,
					rawLines:  rawLines,
					funcDecl:  fn,
				}
			}
		}
		// Immediately-invoked closure `func() { ... }()` is a statement!
		return parseStmtItem(startOff, endOff, startLine, endLine, rawLines)

	case token.VAR:
		chunk := strings.Join(rawLines, "\n")
		fset := token.NewFileSet()
		var specs []*ast.ValueSpec
		if pf, err := parser.ParseFile(fset, "", "package p\n"+chunk, 0); err == nil {
			for _, d := range pf.Decls {
				if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.VAR {
					for _, sp := range gd.Specs {
						if vs, ok := sp.(*ast.ValueSpec); ok {
							specs = append(specs, vs)
						}
					}
				}
			}
		}
		return &topItem{
			kind:      itemVar,
			startOff:  startOff,
			endOff:    endOff,
			startLine: startLine,
			endLine:   endLine,
			rawLines:  rawLines,
			varDecls:  specs,
		}
	}

	return parseStmtItem(startOff, endOff, startLine, endLine, rawLines)
}

func parseStmtItem(startOff, endOff, startLine, endLine int, rawLines []string) *topItem {
	it := &topItem{
		kind:      itemStmt,
		startOff:  startOff,
		endOff:    endOff,
		startLine: startLine,
		endLine:   endLine,
		rawLines:  rawLines,
	}
	chunk := strings.Join(rawLines, "\n")
	const prefix = "package p\nfunc _() {\n"
	fset := token.NewFileSet()
	pf, err := parser.ParseFile(fset, "", prefix+chunk+"\n}\n", 0)
	if err != nil || len(pf.Decls) == 0 {
		return it
	}
	fn, ok := pf.Decls[0].(*ast.FuncDecl)
	if !ok || fn.Body == nil || len(fn.Body.List) == 0 {
		return it
	}
	if assign, ok := fn.Body.List[0].(*ast.AssignStmt); ok && assign.Tok == token.DEFINE {
		tfile := fset.File(pf.Pos())
		tokOff := tfile.Offset(assign.TokPos) - len(prefix)
		if tokOff >= 0 && tokOff+2 <= len(chunk) && chunk[tokOff:tokOff+2] == ":=" {
			var lhs []string
			allIdents := true
			for _, expr := range assign.Lhs {
				id, ok := expr.(*ast.Ident)
				if !ok {
					allIdents = false
					break
				}
				lhs = append(lhs, id.Name)
			}
			if allIdents && len(lhs) > 0 {
				it.hasDefine = true
				it.defineVars = lhs
				it.definePos = tokOff
			}
		}
	}
	return it
}

// --- Variable Hoisting & Type Inference ---

func resolveHoistedVariables(
	opts LowerOptions,
	items []topItem,
	importAliases map[string]string,
) (map[string]string, map[string]bool) {
	// 1. Collect all identifier names referenced inside top-level `func` bodies
	referencedInFuncs := make(map[string]bool)
	for _, it := range items {
		if it.kind == itemFunc && it.funcDecl != nil && it.funcDecl.Body != nil {
			ast.Inspect(it.funcDecl.Body, func(n ast.Node) bool {
				if id, ok := n.(*ast.Ident); ok {
					referencedInFuncs[id.Name] = true
				}
				return true
			})
		}
	}

	// 2. Fixpoint: determine which top-level variables belong in `hoistSet`
	hoistSet := make(map[string]bool)
	for _, it := range items {
		if it.kind == itemVar {
			for _, vs := range it.varDecls {
				for _, id := range vs.Names {
					if id.Name != "_" {
						hoistSet[id.Name] = true
					}
				}
			}
		}
	}

	changed := true
	for changed {
		changed = false
		for _, it := range items {
			if it.kind == itemStmt && it.hasDefine {
				touches := false
				for _, v := range it.defineVars {
					if v != "_" && (referencedInFuncs[v] || hoistSet[v]) {
						touches = true
						break
					}
				}
				if touches {
					for _, v := range it.defineVars {
						if v != "_" && !hoistSet[v] {
							hoistSet[v] = true
							changed = true
						}
					}
				}
			}
		}
	}

	if len(hoistSet) == 0 {
		return nil, hoistSet
	}

	// 3. Fast syntactic type inference
	hoistedTypes := make(map[string]string, len(hoistSet))
	needsTypecheck := false

	for _, it := range items {
		if it.kind == itemVar {
			for _, vs := range it.varDecls {
				if vs.Type != nil {
					ts := formatExprNode(vs.Type)
					for _, id := range vs.Names {
						if id.Name != "_" && hoistedTypes[id.Name] == "" {
							hoistedTypes[id.Name] = ts
						}
					}
					continue
				}
				for idx, id := range vs.Names {
					if id.Name == "_" || hoistedTypes[id.Name] != "" {
						continue
					}
					if idx < len(vs.Values) {
						if t := inferSyntacticExprType(vs.Values[idx], opts.Config); t != "" {
							hoistedTypes[id.Name] = t
							continue
						}
					}
					needsTypecheck = true
				}
			}
		} else if it.kind == itemStmt && it.hasDefine && stmtTouchesHoisted(it.defineVars, hoistSet) {
			rhsExprs := parseDefineRhsExprs(strings.Join(it.rawLines, "\n"))
			if len(rhsExprs) == len(it.defineVars) {
				for idx, vname := range it.defineVars {
					if vname == "_" || hoistedTypes[vname] != "" {
						continue
					}
					if t := inferSyntacticExprType(rhsExprs[idx], opts.Config); t != "" {
						hoistedTypes[vname] = t
					} else {
						needsTypecheck = true
					}
				}
			} else {
				for _, vname := range it.defineVars {
					if vname != "_" && hoistedTypes[vname] == "" {
						needsTypecheck = true
					}
				}
			}
		}
	}

	if needsTypecheck {
		inferred := inferTypesViaGoTypes(opts, items, importAliases)
		for k, v := range inferred {
			if hoistedTypes[k] == "" && v != "" {
				hoistedTypes[k] = v
			}
		}
	}

	return hoistedTypes, hoistSet
}

func inferSyntacticExprType(expr ast.Expr, cfg *pklschema.CompiledConfig) string {
	switch e := expr.(type) {
	case *ast.BasicLit:
		switch e.Kind {
		case token.STRING:
			return "string"
		case token.INT:
			return "int"
		case token.FLOAT:
			return "float64"
		case token.CHAR:
			return "rune"
		}
	case *ast.Ident:
		if e.Name == "true" || e.Name == "false" {
			return "bool"
		}
	case *ast.CompositeLit:
		if e.Type != nil {
			return formatExprNode(e.Type)
		}
	case *ast.UnaryExpr:
		if e.Op == token.AND {
			if cl, ok := e.X.(*ast.CompositeLit); ok && cl.Type != nil {
				return "*" + formatExprNode(cl.Type)
			}
		}
		if e.Op == token.SUB || e.Op == token.ADD {
			return inferSyntacticExprType(e.X, cfg)
		}
		if e.Op == token.NOT {
			return "bool"
		}
	case *ast.CallExpr:
		switch fn := e.Fun.(type) {
		case *ast.Ident:
			switch fn.Name {
			case "string", "int", "int8", "int16", "int32", "int64",
				"uint", "uint8", "uint16", "uint32", "uint64",
				"float32", "float64", "bool", "byte", "rune":
				return fn.Name
			case "new":
				if len(e.Args) == 1 {
					if t := inferSyntacticExprType(e.Args[0], cfg); t != "" {
						return "*" + t
					}
					return "*" + formatExprNode(e.Args[0])
				}
			case "make":
				if len(e.Args) >= 1 {
					return formatExprNode(e.Args[0])
				}
			}
		case *ast.ArrayType:
			return formatExprNode(fn)
		case *ast.SelectorExpr:
			if pkgIdent, ok := fn.X.(*ast.Ident); ok {
				switch pkgIdent.Name + "." + fn.Sel.Name {
				case "fmt.Sprintf", "fmt.Sprint", "fmt.Sprintln",
					"os.Getenv", "strings.TrimSpace", "strings.Join",
					"strings.ToLower", "strings.ToUpper", "filepath.Join",
					"filepath.Dir", "filepath.Base", "filepath.Clean":
					return "string"
				}
			}
		}
	case *ast.SelectorExpr:
		if cfg != nil {
			if t := lookupConfigSelectorType(e, cfg); t != "" {
				return t
			}
		}
	case *ast.BinaryExpr:
		switch e.Op {
		case token.EQL, token.NEQ, token.LSS, token.GTR, token.LEQ, token.GEQ, token.LAND, token.LOR:
			return "bool"
		case token.ADD, token.SUB, token.MUL, token.QUO:
			lt := inferSyntacticExprType(e.X, cfg)
			rt := inferSyntacticExprType(e.Y, cfg)
			if lt != "" && lt == rt {
				return lt
			}
		}
	}
	return ""
}

func lookupConfigSelectorType(sel *ast.SelectorExpr, cfg *pklschema.CompiledConfig) string {
	var chain []string
	cur := ast.Expr(sel)
	for {
		if s, ok := cur.(*ast.SelectorExpr); ok {
			chain = append([]string{s.Sel.Name}, chain...)
			cur = s.X
			continue
		}
		if id, ok := cur.(*ast.Ident); ok {
			if id.Name != cfg.VarName {
				return ""
			}
			break
		}
		return ""
	}
	fields := cfg.RootFields
	var meta *pklschema.FieldMeta
	for _, part := range chain {
		if fields == nil {
			return ""
		}
		m, ok := fields[part]
		if !ok {
			return ""
		}
		meta = m
		fields = m.Children
	}
	if meta != nil {
		return meta.GoType
	}
	return ""
}

func inferTypesViaGoTypes(
	opts LowerOptions,
	items []topItem,
	importAliases map[string]string,
) map[string]string {
	out := make(map[string]string)

	// Build a synthetic Go file where top-level functions have stub `{ panic(0) }` bodies
	// (breaking any dependency on not-yet-hoisted globals!) and all top-level var/`:=`/stmts
	// appear sequentially inside `func _werkInfer()`.
	var sb strings.Builder
	sb.WriteString("package main\n\n")
	if opts.Config != nil && opts.Config.NeedsTimeImport {
		sb.WriteString("import _werk_time \"time\"\n")
	}
	for _, it := range items {
		if it.kind == itemImport {
			sb.WriteString(strings.Join(it.rawLines, "\n") + "\n")
		}
	}
	if opts.Config != nil && opts.Config.GoDecls != "" {
		sb.WriteString(opts.Config.GoDecls + "\n")
	}
	for _, it := range items {
		switch it.kind {
		case itemType, itemConst:
			sb.WriteString(strings.Join(it.rawLines, "\n") + "\n")
		case itemFunc:
			if it.funcDecl != nil {
				stub := *it.funcDecl
				if stub.Type != nil && stub.Type.Results != nil && len(stub.Type.Results.List) > 0 {
					stub.Body = &ast.BlockStmt{
						List: []ast.Stmt{
							&ast.ExprStmt{X: &ast.CallExpr{Fun: ast.NewIdent("panic"), Args: []ast.Expr{ast.NewIdent("0")}}},
						},
					}
				} else {
					stub.Body = &ast.BlockStmt{}
				}
				sb.WriteString(formatDeclNode(&stub) + "\n")
			}
		}
	}
	sb.WriteString("func _werkInfer() {\n")
	for _, it := range items {
		if it.kind == itemVar || it.kind == itemStmt {
			sb.WriteString(strings.Join(it.rawLines, "\n") + "\n")
		}
	}
	sb.WriteString("}\n")

	synthSrc := sb.String()
	fset := token.NewFileSet()
	pf, err := parser.ParseFile(fset, "werk_infer.go", synthSrc, 0)
	if err != nil {
		return out
	}

	info := &types.Info{
		Defs: make(map[*ast.Ident]types.Object),
	}

	// Try fast stdlib/gcimporter first; fall back to `go/packages` if external modules are imported
	conf := types.Config{
		Importer:         importer.Default(),
		DisableUnusedImportCheck: true,
		Error:            func(error) {},
	}
	_, _ = conf.Check("main", fset, []*ast.File{pf}, info)

	// Build reverse map pkgPath -> local import name
	pkgPathToLocal := make(map[string]string)
	for local, path := range importAliases {
		pkgPathToLocal[path] = local
	}
	qual := func(p *types.Package) string {
		if p == nil || p.Name() == "main" {
			return ""
		}
		if local, ok := pkgPathToLocal[p.Path()]; ok {
			return local
		}
		return p.Name()
	}

	extractDefsFromInferFunc(pf, info, qual, out)

	// If any defs resolved to `invalid type` and WorkDir has external modules, try `go/packages` overlay
	hasInvalid := false
	for _, v := range out {
		if strings.Contains(v, "invalid type") {
			hasInvalid = true
			delete(out, v)
		}
	}
	for k, v := range out {
		if strings.Contains(v, "invalid type") {
			delete(out, k)
			hasInvalid = true
		}
	}
	if hasInvalid && opts.WorkDir != "" {
		inferViaGoPackages(opts.WorkDir, synthSrc, qual, out)
	}

	return out
}

func extractDefsFromInferFunc(
	pf *ast.File,
	info *types.Info,
	qual types.Qualifier,
	out map[string]string,
) {
	for _, d := range pf.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || fn.Name == nil || fn.Name.Name != "_werkInfer" || fn.Body == nil {
			continue
		}
		for _, stmt := range fn.Body.List {
			switch s := stmt.(type) {
			case *ast.DeclStmt:
				if gd, ok := s.Decl.(*ast.GenDecl); ok && gd.Tok == token.VAR {
					for _, sp := range gd.Specs {
						if vs, ok := sp.(*ast.ValueSpec); ok {
							for _, id := range vs.Names {
								recordTypedIdent(id, info, qual, out)
							}
						}
					}
				}
			case *ast.AssignStmt:
				if s.Tok == token.DEFINE {
					for _, lhs := range s.Lhs {
						if id, ok := lhs.(*ast.Ident); ok {
							recordTypedIdent(id, info, qual, out)
						}
					}
				}
			}
		}
	}
}

func recordTypedIdent(id *ast.Ident, info *types.Info, qual types.Qualifier, out map[string]string) {
	if id == nil || id.Name == "_" || out[id.Name] != "" {
		return
	}
	obj := info.Defs[id]
	if obj == nil || obj.Type() == nil {
		return
	}
	t := types.Default(obj.Type())
	ts := types.TypeString(t, qual)
	if ts != "" && !strings.Contains(ts, "invalid type") {
		out[id.Name] = ts
	}
}

func inferViaGoPackages(workDir, synthSrc string, qual types.Qualifier, out map[string]string) {
	absDir, err := filepath.Abs(workDir)
	if err != nil {
		return
	}
	fakePath := filepath.Join(absDir, "_werk_typeinfer_tmp.go")
	cfg := &packages.Config{
		Mode: packages.NeedTypes | packages.NeedTypesInfo | packages.NeedSyntax,
		Dir:  absDir,
		Overlay: map[string][]byte{
			fakePath: []byte(synthSrc),
		},
		Env: os.Environ(),
	}
	pkgs, err := packages.Load(cfg, "file="+fakePath)
	if err != nil || len(pkgs) == 0 {
		return
	}
	pkg := pkgs[0]
	for _, syn := range pkg.Syntax {
		extractDefsFromInferFunc(syn, pkg.TypesInfo, qual, out)
	}
}

// --- AST / Source Rewriting Helpers ---

func varHasNoValues(specs []*ast.ValueSpec) bool {
	if len(specs) == 0 {
		return false
	}
	for _, vs := range specs {
		if len(vs.Values) > 0 {
			return false
		}
	}
	return true
}

func stmtTouchesHoisted(vars []string, hoistSet map[string]bool) bool {
	for _, v := range vars {
		if hoistSet[v] {
			return true
		}
	}
	return false
}

func rewriteDefineToAssign(it topItem) []string {
	chunk := strings.Join(it.rawLines, "\n")
	if it.definePos >= 0 && it.definePos+2 <= len(chunk) && chunk[it.definePos:it.definePos+2] == ":=" {
		// Replace `:=` (2 bytes) with ` =` (2 bytes) to preserve exact column coordinates!
		rewritten := chunk[:it.definePos] + " =" + chunk[it.definePos+2:]
		return strings.Split(rewritten, "\n")
	}
	return it.rawLines
}

func rewriteVarToAssignments(it topItem) []string {
	var out []string
	for _, vs := range it.varDecls {
		if len(vs.Values) == 0 {
			continue
		}
		var lhsNames []string
		for _, id := range vs.Names {
			lhsNames = append(lhsNames, id.Name)
		}
		var rhsExprs []string
		for _, val := range vs.Values {
			rhsExprs = append(rhsExprs, formatExprNode(val))
		}
		stmt := fmt.Sprintf("%s = %s", strings.Join(lhsNames, ", "), strings.Join(rhsExprs, ", "))
		out = append(out, strings.Split(stmt, "\n")...)
	}
	return out
}

func parseDefineRhsExprs(stmtSrc string) []ast.Expr {
	fset := token.NewFileSet()
	pf, err := parser.ParseFile(fset, "", "package p\nfunc _() {\n"+stmtSrc+"\n}\n", 0)
	if err != nil || len(pf.Decls) == 0 {
		return nil
	}
	fn, ok := pf.Decls[0].(*ast.FuncDecl)
	if !ok || fn.Body == nil || len(fn.Body.List) == 0 {
		return nil
	}
	if assign, ok := fn.Body.List[0].(*ast.AssignStmt); ok {
		return assign.Rhs
	}
	return nil
}

func extractImportPaths(importSrc string) ([]string, map[string]string) {
	fset := token.NewFileSet()
	pf, err := parser.ParseFile(fset, "", "package p\n"+importSrc, parser.ImportsOnly)
	if err != nil {
		return nil, nil
	}
	var paths []string
	aliases := make(map[string]string)
	for _, imp := range pf.Imports {
		p := strings.Trim(imp.Path.Value, `"`)
		paths = append(paths, p)
		local := filepath.Base(p)
		if imp.Name != nil && imp.Name.Name != "_" && imp.Name.Name != "." {
			local = imp.Name.Name
		}
		aliases[local] = p
	}
	sort.Strings(paths)
	return paths, aliases
}

func formatExprNode(expr ast.Expr) string {
	var buf bytes.Buffer
	_ = printer.Fprint(&buf, token.NewFileSet(), expr)
	return buf.String()
}

func formatDeclNode(decl ast.Decl) string {
	var buf bytes.Buffer
	_ = printer.Fprint(&buf, token.NewFileSet(), decl)
	return buf.String()
}
